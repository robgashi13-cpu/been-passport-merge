const norm = (s: string) => s.toLowerCase().normalize("NFD").replace(/\p{Diacritic}/gu, "");

/**
 * Search airports by IATA / city / country / name. Returns the best matches first.
 * Used by the AI Travel Search modal's autocomplete combobox.
 */
export function searchAirports(query: string, limit = 8): Airport[] {
    const q = norm(query.trim());
    if (!q) return [];
    const exactIata = AIRPORTS.find(a => a.iata.toLowerCase() === q);
    const out: Airport[] = exactIata ? [exactIata] : [];
    for (const a of AIRPORTS) {
        if (out.includes(a)) continue;
        const iata = a.iata.toLowerCase();
        const city = norm(a.city);
        const country = norm(a.country);
        const name = norm(a.name);
        let score = -1;
        if (iata.startsWith(q)) score = 10;
        else if (city.startsWith(q)) score = 9;
        else if (city.includes(q)) score = 7;
        else if (country.startsWith(q)) score = 6;
        else if (name.includes(q)) score = 5;
        else if (country.includes(q)) score = 4;
        if (score >= 0) out.push(a);
        if (out.length >= limit * 3) break;
    }
    return out.slice(0, limit);
}

